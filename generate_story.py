def generate_story(theme: dict) -> str:
    """Claude APIでストーリーを生成する"""
    client = anthropic.Anthropic()

    user_message = f"""今日のインスタストーリーを作成してください。

【何を言うか】：{theme['what']}

【どう言うか】：{theme['how']}"""

    message = client.messages.create(
        model="claude-opus-4-6",
        max_tokens=4096,
        system=SYSTEM_PROMPT,
        messages=[
            {"role": "user", "content": user_message}
        ]
    )

    return message.content[0].text


def save_story(content: str, date_str: str) -> str:
    """ストーリーをファイルに保存する"""
    os.makedirs("stories", exist_ok=True)
    file_path = f"stories/{date_str}.md"

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(f"# みかみストーリー - {date_str}\n\n")
        f.write(content)

    return file_path


def main():
    print(f"みかみストーリー生成開始: {date_str} (曜日: {['月','火','水','木','金','土','日'][weekday]})")

    theme = DAILY_THEMES[weekday]
    print(f"テーマ: {theme['what'][:50]}...")

    print("Claude APIでストーリーを生成中...")
    story = generate_story(theme)

    file_path = save_story(story, date_str)
    print(f"ストーリーを保存しました: {file_path}")

    print("\n--- 生成されたストーリー ---")
    print(story)


